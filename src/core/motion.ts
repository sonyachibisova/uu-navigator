/**
 * Настройка системы «поменьше движения».
 *
 * Человек мог попросить операционную систему обходиться без анимации —
 * из-за вестибулярных нарушений, укачивания или просто по вкусу. Движок это
 * уважает: переходы применяются мгновенно, а конечная картинка остаётся та же.
 * Отдельного «упрощённого режима» с другим результатом у нас нет.
 */

/** Просил ли человек обойтись без анимации. */
export function prefersReducedMotion(): boolean {
  try {
    return window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  } catch {
    // Медиазапросы недоступны (например, в тестовой среде) — считаем, что анимация разрешена.
    return false;
  }
}
