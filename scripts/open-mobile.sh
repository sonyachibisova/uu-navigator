#!/usr/bin/env bash
# Открывает уже запущенный dev-сервер (`npm run dev`) в отдельном окне Chrome
# размером с телефон — портрет, без адресной строки и вкладок (--app).
#
# Раньше при правках приходилось каждый раз открывать localhost на телефоне,
# чтобы увидеть портретную раскладку: на широком окне компьютера всегда
# показывается альбомный вариант (`@media (orientation: landscape)` в
# `src/ui/minimal.ts`). Окно нужной формы включает портретную раскладку
# и портретный ракурс камеры (`PORTRAIT_VIEW` в `src/core/camera.ts`)
# сами — это обычные media-запросы браузера, а не отдельный режим.
#
# Не влияет на определение мобильной платформы в коде (`isMobileLike` в
# `src/core/renderer.ts`): оно смотрит на тип указателя (мышь vs палец),
# а не на форму окна, поэтому качество рендера (сглаживание, тени,
# плотность пикселей) в этом окне остаётся десктопным. На раскладку
# и то, что нужно проверять по картинке, это не влияет.
set -euo pipefail

PORT="${1:-5173}"
URL="http://localhost:${PORT}"
# Габарит близкий к iPhone 15/14 в CSS-пикселях.
WIDTH=393
HEIGHT=852

if ! command -v open >/dev/null 2>&1; then
  echo "Скрипт рассчитан на macOS (команда open). Откройте ${URL} в окне ${WIDTH}x${HEIGHT} вручную." >&2
  exit 1
fi

open -na "Google Chrome" --args \
  --new-window \
  --app="${URL}" \
  --window-size="${WIDTH},${HEIGHT}"
