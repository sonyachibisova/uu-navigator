#!/usr/bin/env bash
# Открывает уже запущенный dev-сервер (`npm run dev`) на странице
# `public/dev-mobile.html` — телефонная рамка фиксированного размера
# с портретной раскладкой внутри. Рамка не зависит от размера окна
# браузера: можно держать вкладку развёрнутой на весь экран, внутри
# рамки всё равно портрет.
#
# Открывает в отдельном окне без адресной строки и вкладок (--app),
# но это только для удобства просмотра — портретность даёт сама
# страница, а не форма окна (см. комментарий в dev-mobile.html).
#
# Не влияет на определение мобильной платформы в коде (`isMobileLike` в
# `src/core/renderer.ts`): оно смотрит на тип указателя (мышь vs палец),
# а не на форму окна, поэтому качество рендера (сглаживание, тени,
# плотность пикселей) остаётся десктопным. На раскладку это не влияет.
set -euo pipefail

PORT="${1:-5173}"
URL="http://localhost:${PORT}/dev-mobile.html"

if ! command -v open >/dev/null 2>&1; then
  echo "Скрипт рассчитан на macOS (команда open). Откройте ${URL} в браузере вручную." >&2
  exit 1
fi

open -na "Google Chrome" --args \
  --new-window \
  --app="${URL}" \
  --window-size=460,940
